/**
 * Determines whether a school record represents a Primary School Grade R / Reception Unit
 */
export function isPrimarySchoolGradeR(school: Partial<Preschool> | any): boolean {
  if (!school) return false;
  if (school.institutionType === 'primary-grade-r') return true;
  if (school.gradeRDetails?.hasDedicatedReceptionUnit) return true;

  const text = `${school.name || ''} ${school.tagline || ''} ${school.description || ''}`.toLowerCase();
  // Match explicit primary/preparatory/junior school Grade R or Reception Unit patterns
  if (
    /\b(d\.?p\.?h\.?s|durban preparatory|reception unit|little bosch)\b/i.test(text) ||
    (/\b(primary school|preparatory school|prep school|junior primary|junior school|laerskool|college primary)\b/i.test(
      text
    ) &&
      !/\bpre-primary\b/i.test(school.name || ''))
  ) {
    return true;
  }
  return false;
}
